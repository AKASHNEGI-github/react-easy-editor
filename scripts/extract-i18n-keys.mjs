// Builds the list of translatable UI strings straight from the source, so the English template
// can never drift from the code.
//
//   node scripts/extract-i18n-keys.mjs           prints the keys
//   node scripts/extract-i18n-keys.mjs --write   regenerates src/locales/en.js
//
// A string is a key when it is passed to t() (`editor.t('...')`, including strings in an
// `a ? editor.t('x') : editor.t('y')` ternary) or when a plugin declares it as a tooltip, a
// dropdown label or a placeholder. Font names are proper names and are not keys.
// The table menus keep their `label:` lists in the component files named in COMPONENT_LABELS.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'src');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) return name === 'styles' || name === 'locales' ? [] : walk(full);
    return /\.(js|jsx)$/.test(name) ? [full] : [];
  });
}

// A JS string literal in single OR double quotes, escapes resolved later (\u2019, \', ...).
const QUOTES = [String.raw`'((?:[^'\\\n]|\\.)*)'`, String.raw`"((?:[^"\\\n]|\\.)*)"`];
const unescape = (s) => s.replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16))).replace(/\\(.)/g, '$1');

const regexesFor = (STR) => ({
  call: new RegExp(String.raw`\b(?:editor\.)?t\(\s*${STR}`, 'g'),
  // t(cond ? 'one' : 'two', ...)  (the status bar's singular / plural)
  ternary: new RegExp(String.raw`\b(?:editor\.)?t\(\s*[^()'"`+'`'+String.raw`]*?\?\s*${STR}\s*:\s*${STR}`, 'g'),
  prop: new RegExp(String.raw`\b(?:tooltip|label|placeholder)\s*:\s*${STR}`, 'g'),
});
const REGEXES = QUOTES.map(regexesFor);
const arrowTooltipRe = new RegExp(String.raw`'(Switch to [a-z]+ theme)'`, 'g');
const FONT_FILE = /plugins[\\/]font\.js$/;
// Components that declare `label:` lists and translate them when rendering (editor.t(item.label)).
const COMPONENT_LABELS = /components[\\/](TableTools|TableColorPopup)\.jsx$/;

export function extractKeys() {
  const keys = new Set();
  for (const file of walk(SRC)) {
    const text = readFileSync(file, 'utf8');
    const isPlugin = /[\\/]plugins[\\/]/.test(file) || /alertUtils\.js$/.test(file) || /highlight\.js$/.test(file) || COMPONENT_LABELS.test(file);
    for (const re of REGEXES) {
      for (const m of text.matchAll(re.call)) keys.add(unescape(m[1]));
      for (const m of text.matchAll(re.ternary)) {
        keys.add(unescape(m[1]));
        keys.add(unescape(m[2]));
      }
      if (!isPlugin) continue;
      for (const m of text.matchAll(re.prop)) {
        const value = unescape(m[1]);
        // font family / size names are proper names and numbers, not words to translate
        if (FONT_FILE.test(file) && value !== 'Default' && !/^(Font|Size|Font family|Font size)$/.test(value)) continue;
        // programming-language names are proper nouns; only "Plain text" is a word
        if (/highlight\.js$/.test(file) && value !== 'Plain text') continue;
        keys.add(value);
      }
    }
    if (isPlugin) for (const m of text.matchAll(arrowTooltipRe)) keys.add(m[1]);
    // The emoji picker's category tabs come from an array and are translated when rendered.
    if (/EmojiPickerForm\.jsx$/.test(file)) {
      const cats = /const CATEGORIES = \[([^\]]*)\]/.exec(text);
      if (cats) for (const m of cats[1].matchAll(new RegExp(QUOTES[0], 'g'))) keys.add(unescape(m[1]));
    }
  }
  return [...keys].filter((k) => /[A-Za-z]/.test(k)).sort((a, b) => a.localeCompare(b, 'en'));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const keys = extractKeys();
  if (process.argv.includes('--write')) {
    const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const body = keys.map((k) => `  ${q(k)}: ${q(k)},`).join('\n');
    writeFileSync(
      path.join(SRC, 'locales', 'en.js'),
      `// GENERATED by scripts/extract-i18n-keys.mjs --write. Do not edit by hand.\n` +
        `// Every string the editor shows, mapped to itself. Copy this file to start a translation:\n` +
        `// change the right-hand sides and pass the result as <Editor translations={...} />.\n` +
        `// {count}-style placeholders must be kept. Anything you leave out simply stays English.\n` +
        `export const localeEn = {\n${body}\n};\n`
    );
    console.log(`wrote src/locales/en.js with ${keys.length} keys`);
  } else {
    console.log(keys.join('\n'));
    console.error(`\n${keys.length} keys`);
  }
}
