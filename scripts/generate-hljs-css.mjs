// Generates src/styles/hljs-scoped.css from highlight.js's own theme files.
//
// highlight.js themes are global stylesheets (`.hljs-keyword { ... }`).
// Injecting them as-is would restyle every other highlight.js block on the
// host page, and the host's own theme would in turn restyle ours. This
// script prefixes every selector so the colors only apply inside an editor:
//
//   light:  .jc-root:not([data-theme='dark']) .hljs-keyword
//   dark:   .jc-root[data-theme='dark'] .hljs-keyword
//
// Both themes ship in the one stylesheet, so switching theme is just the
// `data-theme` attribute changing — no runtime <style> tag, no JS, and it
// works with server rendering and strict Content-Security-Policy.
//
// The layout rules highlight.js puts in every theme (`pre code.hljs`,
// `code.hljs`) are dropped on purpose: the editor styles its own code
// blocks in editor.css and those rules would fight it.
//
// Run:  npm run build:hljs-css     (only needed when highlight.js is upgraded)

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const stylesDir = join(dirname(require.resolve('highlight.js/package.json')), 'styles');
const version = require('highlight.js/package.json').version;

const THEMES = [
  { file: 'github.css', prefix: ".jc-root:not([data-theme='dark'])", label: 'light (github.css)' },
  { file: 'github-dark.css', prefix: ".jc-root[data-theme='dark']", label: 'dark (github-dark.css)' },
];

const LAYOUT_ONLY = new Set(['pre code.hljs', 'code.hljs']);

function scope(css, prefix) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(withoutComments))) {
    const selectors = m[1].split(',').map((s) => s.trim().replace(/\s+/g, ' ')).filter(Boolean);
    const body = m[2].trim().replace(/\s*\n\s*/g, ' ');
    if (!body) continue; // e.g. the "purposely ignored" empty rule
    const kept = selectors.filter((s) => !LAYOUT_ONLY.has(s));
    if (!kept.length) continue;
    rules.push(`${kept.map((s) => `${prefix} ${s}`).join(',\n')} {\n  ${body.replace(/;\s*/g, ';\n  ').trim()}\n}`);
  }
  return rules.join('\n');
}

let out = `/* GENERATED by scripts/generate-hljs-css.mjs from highlight.js ${version} — do not edit by hand.
   Re-run \`npm run build:hljs-css\` after upgrading highlight.js.
   Every selector is scoped to the editor root so these colors can never
   leak onto (or be overridden by) other highlight.js blocks on the page. */\n`;

for (const t of THEMES) {
  const css = readFileSync(join(stylesDir, t.file), 'utf8');
  out += `\n/* ${t.label} */\n${scope(css, t.prefix)}\n`;
}

const target = join(here, '..', 'src', 'styles', 'hljs-scoped.css');
writeFileSync(target, out);
console.log(`wrote ${target} (${out.length} bytes)`);
