const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
function escapeText(str) {
  return String(str).replace(/[&<>"']/g, (ch) => ESCAPES[ch]);
}

// Returns safe HTML. A language we did not register (or that fails to parse)
// degrades to escaped plain text, never to a wrong-looking guess.
export function highlightCode(code, language) {
  if (!hljs.getLanguage(language)) return escapeText(code);
  try {
    return hljs.highlight(code, { language, ignoreIllegals: true }).value;
  } catch {
    return escapeText(code);
  }
}
